"""Build a public-only handoff kit, never access a private checkout."""
from __future__ import annotations

import argparse
import shutil
import sys

from common import BASE, digest, local_path, read_json, read_jsonl, write_json

sys.path.insert(0, str(BASE / "holdout_support"))
from contract import exclusion_index, holdout_schema

TOOLS = ("common.py", "edit_contract.py", "validate.py", "score.py", "run.py", "review_packet.py")
SUPPORT = ("adapter.py", "contract.py", "README.md", "synthetic_smoke.py")


def build_kit(output):
    output = local_path(BASE, output)
    if not output.is_relative_to(BASE / "results"):
        raise ValueError("handoff kits must be under ignored public v2/results/")
    if output.exists():
        raise ValueError("refusing to overwrite a handoff kit")
    cases = read_jsonl(BASE / "dev.jsonl") + read_jsonl(BASE / "test.jsonl")
    sources = {"pinned/scripts/" + name: BASE / "scripts" / name for name in TOOLS}
    sources.update({name: BASE / "holdout_support" / name for name in SUPPORT})
    sources.update({"pinned/" + name: BASE / name for name in ("schema.json", "unit_rules.json")})
    for target, source in sources.items():
        dest = output / target
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
    write_json(output / "holdout-schema.json", holdout_schema(read_json(BASE / "schema.json")))
    rules = read_json(BASE / "unit_rules.json")["rules"]
    definitions = [(r["definition_sha256"], r["locator"]) for r in rules]
    write_json(output / "public-exclusions.json", exclusion_index(cases, lambda p: read_json(local_path(BASE, p)), definitions))
    write_json(output / "feature-contract.json", {
        "ai_assisted": True, "basis": read_json(BASE / "dataset_policy.json")["revision"],
        "api_sequence": ["/api/query execute=True", "returned state + user period", "/api/output", "/api/output/edit"],
        "session_policy": "Only runtime-issued sessions; input only reaches the product.",
        "file_upload": False, "automatic_prior_dialogue": False,
        "chart_types": ["line", "bar", "area", "stacked_bar"], "layouts": ["combined", "separate"],
        "holdout_mode_counts": {"discovery": 6, "e2e": 8, "output": 3, "edit": 1},
        "holdout_edit": "set_title", "period_policy": "absolute, exact, source-verified",
        "offline_edit_parser": "input command replay, not natural-language accuracy",
        "production_claim": "Neither browser UI nor live KOSIS/NCP verification"})
    files = {str(p.relative_to(output)).replace("\\", "/"): digest(p)
             for p in sorted(output.rglob("*")) if p.is_file()}
    manifest = {"ai_assisted": True, "private_cases_created": 0, "production_status": "handoff_only",
                "public_dataset_hashes": {s: digest(BASE / (s + ".jsonl")) for s in ("dev", "test")},
                "files": files, "annotation_policy": "No human approval is generated by tooling."}
    write_json(output / "bundle-manifest.json", manifest)
    return {"kit": str(output), "files": len(files), "private_cases_created": 0,
            "manifest_sha256": digest(output / "bundle-manifest.json")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    print(build_kit(args.output))


if __name__ == "__main__":
    main()
